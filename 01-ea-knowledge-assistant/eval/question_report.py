"""Render a question-by-question test report from an evaluation run.

    python eval/question_report.py claude              # reads results/claude.json
    python eval/question_report.py offline_baseline

run_eval.py calls this automatically, so results/<tag>_questions.md is rewritten on every run.
Nothing here re-scores anything: every verdict comes from the checks already stored in
results/<tag>.json. Hand-written explanations live in eval/failure_notes.yaml and are shown
separately, labelled as analysis written after the run.
"""
from __future__ import annotations

import json
import re
import sys
from collections import OrderedDict
from pathlib import Path

import yaml

EVAL = Path(__file__).resolve().parent
GROUNDED_CUTOFF = 0.9  # same rule as run_eval: >= 90% of factual sentences cited and supported

PASS, PARTIAL, FAIL = "PASS", "PARTIAL", "FAIL"
ICON = {PASS: "✅", PARTIAL: "🟡", FAIL: "❌"}


def _clean(text: str) -> str:
    """Normalise dashes for display (the repo style avoids em/en dashes) and collapse whitespace."""
    text = text.replace(" \u2014 ", " - ").replace("\u2014", " - ").replace("\u2013", "-")
    return text


def _one_line(text: str, n: int = 140) -> str:
    t = re.sub(r"[#*`>]", "", _clean(text))
    t = re.sub(r"\s+", " ", t).strip()
    return t if len(t) <= n else t[: n - 1].rstrip() + "…"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def load_queries() -> tuple[dict, dict]:
    """Return {id: query} and {id: category}, taking the category from the section comments."""
    raw = (EVAL / "queries.yaml").read_text(encoding="utf-8")
    cats, current = {}, "Uncategorised"
    for line in raw.splitlines():
        m = re.match(r"\s*#\s*-{5,}\s*(.+?)\s*$", line)
        if m:
            current = m.group(1).strip()
            current = current[0].upper() + current[1:]
        m = re.match(r"\s*-\s*id:\s*(\S+)", line)
        if m:
            cats[m.group(1)] = current
    qs = {q["id"]: q for q in yaml.safe_load(raw)["queries"]}
    return qs, cats


def load_notes(tag: str) -> dict:
    p = EVAL / "failure_notes.yaml"
    if not p.exists():
        return {}
    data = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
    return data.get(tag, {}) or {}


def doc_of(chunk_id: str) -> str:
    return chunk_id.split("#", 1)[0]


def first_relevant_rank(retrieved: list[str], relevant: list[str]) -> int | None:
    for i, c in enumerate(retrieved, 1):
        if doc_of(c) in relevant:
            return i
    return None


def verdict(row: dict) -> tuple[str, str]:
    """Return (verdict, short reason) from the stored checks."""
    if row["expect"] == "not_found":
        return (PASS, "Correctly refused") if not row["found"] else (FAIL, "Answered instead of refusing")
    if not row["found"]:
        return FAIL, "Wrongly refused"
    if not row.get("keywords_ok"):
        return FAIL, "Key fact missing"
    gd = row.get("groundedness_detail") or {}
    rate = gd.get("supported_rate")
    issues = []
    if not row.get("cites_relevant"):
        issues.append("cited an unlabelled source")
    if rate is not None and rate < GROUNDED_CUTOFF:
        issues.append(f"{round(100 * rate)}% of sentences supported")
    if issues:
        return PARTIAL, "Correct; " + ", ".join(issues)
    return PASS, "Correct and grounded"


def render(tag: str) -> str:
    res = json.loads((EVAL / "results" / f"{tag}.json").read_text(encoding="utf-8"))
    qs, cats = load_queries()
    notes = load_notes(tag)
    rows = res["rows"]
    k = res.get("k", 5)

    enriched = []
    for r in rows:
        q = qs.get(r["id"], {})
        v, why = verdict(r)
        rank = first_relevant_rank(r.get("retrieved", [])[:k], q.get("relevant_docs", [])) if r["expect"] == "answer" else None
        enriched.append({**r, "q": q, "cat": cats.get(r["id"], "Uncategorised"), "verdict": v, "why": why, "rank": rank})

    n = len(enriched)
    counts = {x: sum(e["verdict"] == x for e in enriched) for x in (PASS, PARTIAL, FAIL)}
    e2e = res["end_to_end_test"]
    answers_by = "an LLM" if res["llm_provider"] not in ("extractive",) else "extractive quoting (no LLM)"

    L = [
        f"# Question-by-question test report: `{tag}`",
        "",
        f"Run {res['run_at']} · answers by `{res['llm_provider']}` ({answers_by}) · "
        f"{res['index']['documents']} documents / {res['index']['chunks']} chunks · top-k = {k}",
        "",
        "This page shows **every test question**, what a correct answer had to contain, what the assistant "
        "actually did and which checks it passed. It is generated by `eval/question_report.py` from "
        f"`results/{tag}.json`, so it always matches the summary in [`{tag}.md`]({tag}.md). "
        "For how the method works and how to run an evaluation like this yourself, see "
        "[`../EVALUATION_GUIDE.md`](../EVALUATION_GUIDE.md).",
        "",
        "## 1. How to read this report",
        "",
        "Each question is scored by automatic checks. None of them is a human opinion:",
        "",
        "| Check | Question it answers | How it's decided |",
        "|---|---|---|",
        "| **Rank** | Did search put the right document near the top? | Position (1 to "
        f"{k}) of the first retrieved passage from a labelled document. \"miss\" = none in the top {k}. |",
        "| **Right passage** | Did the passage holding the key fact reach the model? | The key fact appears in a retrieved passage from a labelled document. Rank can be 1 while this is \"no\": right document, wrong section. |",
        "| **Found** | Did the assistant answer, or say \"not found\"? | Answerable questions should be answered; out-of-corpus ones refused. |",
        "| **Key fact** | Is the answer actually right? | The answer text contains the labelled fact (e.g. `2025-06-30`). |",
        "| **Cites source** | Did it cite a document that really answers the question? | At least one citation is a labelled document. |",
        f"| **Support** | Is every claim backed by the passage it cites? | Share of factual sentences that cite a passage and share at least 50% of their content words with it. \"Grounded\" means {int(GROUNDED_CUTOFF*100)}% or more. |",
        "",
        "Verdicts combine those checks:",
        "",
        f"- {ICON[PASS]} **PASS**: answered, key fact present, relevant source cited, grounded (or, for out-of-corpus questions, correctly refused).",
        f"- {ICON[PARTIAL]} **PARTIAL**: the answer is correct, but the evidence trail is weaker than it should be (some sentences uncited, or the citation points to a document outside the labels).",
        f"- {ICON[FAIL]} **FAIL**: wrongly refused, key fact missing, or (for out-of-corpus) answered with a guess.",
        "",
        "## 2. Scorecard",
        "",
        f"| | Count | Share of {n} test questions |",
        "|---|---|---|",
    ]
    for x in (PASS, PARTIAL, FAIL):
        L.append(f"| {ICON[x]} {x} | {counts[x]} | {100 * counts[x] / n:.0f}% |")
    L += [
        "",
        "Headline metrics for the same run (from the summary report):",
        "",
        f"- Key fact in answer: **{100*e2e['answer_contains_key_fact']:.1f}%** of answerable questions",
        f"- Out-of-corpus refused: **{100*e2e['out_of_corpus_refused']:.0f}%**",
        f"- Claim support: **{100*(e2e.get('claim_support_rate') or 0):.1f}%** of factual sentences",
        f"- Fully grounded answers: **{100*(e2e.get('groundedness_rate') or 0):.1f}%**",
        "",
        "### By topic",
        "",
        f"| Topic | Questions | {ICON[PASS]} | {ICON[PARTIAL]} | {ICON[FAIL]} |",
        "|---|---|---|---|---|",
    ]
    by_cat: "OrderedDict[str, list]" = OrderedDict()
    for e in enriched:
        by_cat.setdefault(e["cat"], []).append(e)
    for c, es in by_cat.items():
        L.append(f"| {c} | {len(es)} | " + " | ".join(str(sum(e['verdict'] == x for e in es)) for x in (PASS, PARTIAL, FAIL)) + " |")

    L += [
        "",
        "## 3. All test questions at a glance",
        "",
        "| ID | Topic | Question | Expected | Rank | Right passage | Key fact | Cites source | Support | Verdict |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    yn = lambda b: "n/a" if b is None else ("yes" if b else "**no**")
    for e in enriched:
        q = e["q"]
        if e["expect"] == "answer":
            exp = " or ".join(f"`{_cell(a)}`" for a in q.get("answer_keywords", [""])[0].split("|"))
            rank = str(e["rank"]) if e["rank"] else "**miss**"
            rate = (e.get("groundedness_detail") or {}).get("supported_rate")
            sup = "n/a" if (rate is None or not e["found"]) else f"{round(100 * rate)}%"
            kf, cs = yn(e.get("keywords_ok")), yn(e.get("cites_relevant"))
            rp = yn(e.get("answer_in_context"))
        else:
            exp, rank, sup, kf, cs, rp = "refuse", "n/a", "n/a", "n/a", "n/a", "n/a"
        L.append(f"| [{e['id']}](#{e['id']}) | {e['cat']} | {_cell(q.get('question', ''))} | {exp} | {rank} | {rp} | {kf} | {cs} | {sup} | {ICON[e['verdict']]} {e['why']} |")

    flagged = [e for e in enriched if e["verdict"] != PASS]
    L += ["", "## 4. What went wrong, and why", ""]
    if not flagged:
        L.append("Every test question passed.")
    else:
        L += [
            "Automatic checks say *that* something failed. The notes below say *why*, and were written by "
            "reading the stored answer and retrieved passages after the run. Labels and the rubric were "
            "**not** changed to make these pass.",
            "",
        ]
        for e in flagged:
            note = notes.get(e["id"])
            L.append(f"- **[{e['id']}](#{e['id']})** {ICON[e['verdict']]} {e['why']}. "
                     + (_clean(note.strip()) if note else "_No written analysis yet; see the detail card below._"))
        group = notes.get("_patterns")
        if group:
            L += ["", "**Patterns across the flagged questions**", "", _clean(group.strip())]

    L += ["", "## 5. Detail for every question", "",
          "Each card shows exactly what the assistant saw and said. Open **Answer** to read the full response.", ""]
    for e in enriched:
        q = e["q"]
        L += [f'<a id="{e["id"]}"></a>', "", f"### {e['id']} · {ICON[e['verdict']]} {e['verdict']}: {_clean(q.get('question', ''))}", ""]
        L.append(f"- **Topic:** {e['cat']}")
        if e["expect"] == "answer":
            L.append(f"- **Expected:** an answer containing {' or '.join('`'+a+'`' for a in q.get('answer_keywords',[''])[0].split('|'))}, "
                     f"from {', '.join('`'+d+'`' for d in q.get('relevant_docs', []))}")
        else:
            L.append("- **Expected:** \"not found\". The corpus was written never to cover this topic.")
        retr = e.get("retrieved", [])[:k]
        mark = lambda c: f"**{c}**" if (e["expect"] == "answer" and doc_of(c) in q.get("relevant_docs", [])) else c
        L.append(f"- **Top {k} retrieved passages** (labelled sources in bold): " + ", ".join(mark(c) for c in retr))
        if e["expect"] == "answer":
            L.append(f"- **Answer passage reached the model:** {'yes' if e.get('answer_in_context') else 'no'}")
        L.append(f"- **Result:** {e['why']}")
        if e["found"] and e.get("citations"):
            L.append(f"- **Documents cited:** {', '.join(sorted(set(e['citations'])))}")
        gd = e.get("groundedness_detail") or {}
        bad = [s for s in gd.get("sentences", []) if not s.get("supported")]
        if bad:
            L.append(f"- **Sentences the groundedness check did not accept ({len(bad)}):**")
            for s in bad[:6]:
                reason = s.get("reason") or f"word overlap {s.get('overlap')} below 0.5"
                L.append(f"  - \"{_one_line(s['sentence'], 120)}\" ({reason})")
            if len(bad) > 6:
                L.append(f"  - ...and {len(bad) - 6} more")
        if e["id"] in notes:
            L.append(f"- **Analysis:** {_clean(notes[e['id']].strip())}")
        L += ["", "<details><summary>Answer</summary>", "", _clean(e.get("answer", "")).strip(), "", "</details>", ""]

    L += ["---", "",
          "Dashes in quoted answers are normalised to hyphens for display; the raw text is in "
          f"`results/{tag}.json`."]
    return "\n".join(L) + "\n"


def write(tag: str) -> Path:
    out = EVAL / "results" / f"{tag}_questions.md"
    out.write_text(render(tag), encoding="utf-8")
    return out


if __name__ == "__main__":
    for t in sys.argv[1:] or ["claude", "offline_baseline"]:
        print("wrote", write(t))
